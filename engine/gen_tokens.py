#!/usr/bin/env python3
"""Generate the structure-aware mutator's token tables from the compiler.

    gen_tokens.py TURF_ROOT OUT_DIR

writes OUT_DIR/turf_tokens.inc (C++ arrays for mutator.cpp) and
OUT_DIR/turf.dict (a libFuzzer -dict= file). The keywords come from the
lexer's own table (`{"name", TOK_...}` in src/Lexer.cpp), as tier0/mutate.py
reads them, so a keyword added to the language is fuzzed with no edit here.
Run by CMake at build time.
"""

import re
import sys
from pathlib import Path

PUNCT = ["(", ")", "{", "}", "[", "]", ";", ",", ".", ":", "::", "->", "=", "==", "!=",
         "<", ">", "<=", ">=", "+", "-", "*", "/", "%", "&", "|", "^", "!", "?", "~",
         "<<", ">>", "&&", "||", "+=", "-=", "*=", "/=", "%=", "&=", "|=", "^=", "<<=",
         ">>=", "++", "--", "..", "**", "@", "&?"]
NUMBERS = ["0", "1", "-1", "2", "7", "255", "256", "2147483647", "2147483648",
           "4294967296", "9223372036854775807", "9223372036854775808",
           "-9223372036854775808", "99999999999999999999", "0x10", "0xFFFFFFFFFFFFFFFF",
           "0b101", "1e308", "1e999", "0.0", "0.5", "1.5", "-0.0", "1_000"]
STRINGS = ['""', '"a"', '"\\n"', '"\\t"', '"\\\\"', '"\\q"', "'a'", "'\\n'", "'\\0'"]
TYPES = ["int", "int32", "double", "bool", "char", "string", "void", "int[3]", "int[]",
         "&N", "&?N", "!int", "List<int>", "Map<string, int>", "Set<int>", "Stack<int>",
         "Queue<int>", "S", "N", "E", "T"]
# Names a program commonly reaches for: stdlib modules, functions, methods,
# intrinsics and the generic placeholder. Identifiers otherwise come from the
# input being mutated.
NAMES = ["io", "printline", "print", "flush", "list", "List", "map", "Map", "set", "Set",
         "stack", "Stack", "queue", "Queue", "strings", "math", "sys", "test", "assert",
         "push", "pop", "get", "put", "add", "remove", "contains", "length", "copy",
         "default", "new", "heap", "gc_collect", "message", "main", "x", "y", "n", "p",
         "q", "s", "self", "err", "E0", "A", "B"]
# Whole constructs, inserted as one unit: the mutator's shortcut to syntax that
# byte mutation almost never assembles.
SNIPPETS = [
    "mut x: int = 0;", "immut y: int = x + 1;", "return 0;", "io::printline(x);",
    "if (x > 0) { x = x - 1; } elseif (x < 0) { x = 0; } else { }",
    "while x < 3 { x += 1; }", "for i in 0..3 { x += i; }",
    "mut a: int[3] = [1, 2, 3];", "for v in a { x += v; }",
    "compare (x) { matches 1: x = 2; done otherwise: x = 3; }",
    "defer io::flush();", "break;", "continue;",
    "mut v: int = f(1) recover produce 0;",
    "mut v: int = f(1) recover as err run { return 0; };",
    "struct S { a: int, b: bool }", "enum En { Red, Green }",
    "error E0 { A, B(path: string) }", "fn f(k: int): !int { return E0::A; }",
    "fn<T> g(a: T, b: T): T { return a; }", "fn S.m(k: int): void { self.a = k; }",
    "struct N { val: int, next: &?N }", "mut p: &N = heap(N::default());",
    "mut q: &?N = null;", "if (q != null) { q.val = 1; }",
    "import list::List;", "mut l: List<int> = List::default();", "l.push(1);",
    "unsafe { }", "operator +(a: S, b: S): S { return a; }",
    "mut s: string = \"a\" + (x to string);", "(x > 0 give 1 otherwise 2)",
    "machine M { A, B }", "export immut K: int = 3;", "pub fn h(): int { return 1; }",
    "@caller_location", "mut d: double = 1.5 * (x to double);",
]


def keywords(root):
    text = (Path(root) / "src" / "Lexer.cpp").read_text()
    words = sorted(set(re.findall(r'\{"([a-z_]+)",\s*TOK_', text)))
    if not words:
        sys.exit("no keyword table found in src/Lexer.cpp")
    return words


def c_array(name, items):
    body = ",\n".join("    " + c_str(s) for s in items)
    return "static const char *const %s[] = {\n%s\n};\n" % (name, body)


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def dict_str(s):
    out = []
    for ch in s:
        if ch in '"\\':
            out.append("\\" + ch)
        elif 32 <= ord(ch) < 127:
            out.append(ch)
        else:
            out.append("\\x%02x" % ord(ch))
    return '"' + "".join(out) + '"'


def main():
    root, out = sys.argv[1], Path(sys.argv[2])
    out.mkdir(parents=True, exist_ok=True)
    kw = keywords(root)
    inc = ["// Generated by engine/gen_tokens.py from src/Lexer.cpp; do not edit.\n"]
    for name, items in (("kKeywords", kw), ("kPunct", PUNCT), ("kNumbers", NUMBERS),
                        ("kStrings", STRINGS), ("kTypes", TYPES), ("kNames", NAMES),
                        ("kSnippets", SNIPPETS)):
        inc.append(c_array(name, items))
    (out / "turf_tokens.inc").write_text("".join(inc))
    lines = ["# libFuzzer dictionary for Turf, generated by engine/gen_tokens.py"]
    seen = set()
    for group, items in (("kw", kw), ("p", PUNCT), ("n", NUMBERS), ("s", STRINGS),
                         ("t", TYPES), ("id", NAMES), ("snip", SNIPPETS)):
        for i, s in enumerate(items):
            if s in seen:
                continue
            seen.add(s)
            lines.append("%s_%d=%s" % (group, i, dict_str(s)))
    (out / "turf.dict").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
